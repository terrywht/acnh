C_NEW = """**想刷某一条。**夏天反而慢。9 月河里 37 种鱼，每条平均 2.5 份；1 月只有 16 种，每条 5.9 份。种类多不等于那一条更容易来。

**想要垃圾。**四条垃圾全年都在，份额 1 到 2 份，池子越大越难碰上。全垃圾素材岛的抽取权重只有 10，是三个特殊岛里第二难抽的。真要靠垃圾堆图鉴，这条路的成本比钓鱼高得多。"""

