# -*- coding: utf-8 -*-
import io, re

P = 'docs/文章-动森钓鱼数值拆解-v2.md'
s = io.open(P, encoding='utf-8').read()

# ---------- 3.1 补：影子也预告难度 ----------
A_OLD = """所以稀有度全部押在概率上，操作难度反过来给贵鱼让路。

三个数里还有两个特例。"""

A_NEW = """所以稀有度全部押在概率上，操作难度反过来给贵鱼让路。

这层难度还被影子提前泄露了。LLL 那 7 条，5 条是浮标 1 档；J 那 5 条，3 条是 2 档。反过来，SS 和 S 两档合计 30 条鱼，24 条落在 3 档以上。

影子本来就负责提前告诉你"这竿大概什么货色"。现在这层预告更完整：大影子不光值钱，还好拉；小影子不光便宜，还磨人。两件事在同一个形状里同时透出来，你连猜都不用猜。

三个数里还有两个特例。"""

assert A_OLD in s
s = s.replace(A_OLD, A_NEW)


# ---------- 3.2 补：绕圈 / 专属鱼的动作最统一 ----------
B_OLD = """**抗水流 14 条，全在河系。**河流 7、悬崖上 4、出海口 3，一条海鱼都没有。海里的鱼游的是"一直游"和"绕圈"。这也是河钓和海钓在视觉上的第一分野：河里那些鱼影一直在原地摆尾，顶着水流。"""

B_NEW = """**抗水流 14 条，全在河系。**河流 7、悬崖上 4、出海口 3，一条海鱼都没有。海里的鱼游的是"一直游"和"绕圈"。这也是河钓和海钓在视觉上的第一分野：河里那些鱼影一直在原地摆尾，顶着水流。

**绕圈的 13 条几乎全是小影子，平均影子档 1.8。**金鱼、龙睛金鱼、稻田鱼、霓虹灯鱼、彩虹鱼、神仙鱼、温泉医生鱼、红目鲫、海马、狮子鱼、鲷鱼、条石鲷、河豚。

这一档的共同点是原地打转。它们不是"游过去"的类型，是"待在这一小块地方转圈"的类型。玩家看到的是——池子角落里那几个小影子，一直在同一片水面上绕。

**专属鱼的动作最统一。**悬崖上专属 4 条，全是抗水流；出海口专属 3 条，全是抗水流；栈桥专属 4 条，全是捕食者。三个钓点，三种动作，一条不混。

池塘反过来，12 条鱼里 5 条待机、3 条绕圈、4 条一直游，三种动作混着，没有专属的一种。这也是池塘看着最"家常"的原因：什么都有一点。

所以走进不同钓点，还没抛竿就能判断出这是哪儿。河里满屏顶水摆尾的小影子，池塘一片不动的，栈桥下面有大鱼在追小鱼。第一章说钓点是筛子——筛出来的不只是鱼种，还有水面上这一整套动静。"""

assert B_OLD in s
s = s.replace(B_OLD, B_NEW)


